#!/usr/bin/env python3
"""Fail when the copied design tokens of appkit-ui drift from the tag they are pinned to.

The window has no package manager, so the tokens of appkit-ui (ui-kit/src/tokens.css of
https://github.com/StefanBartl/appkit) are a checked-in copy, src/appkit-tokens.css. The tag is named once, in
tools/appkit-ui.pin, together with the commit it named when the copy was taken. This checks that

  * the tag still names that commit (a moved tag would change the file under the same name);
  * the copy is the kit's file at that commit, byte for byte (line endings aside);
  * src/appkit-tokens-fallback.css is what this script generates from it: the colours of the tokens as plain
    values, for a WebView without light-dark() (see FALLBACK_HEAD).

    python tools/check-appkit-tokens.py                      against GitHub (git ls-remote, then the raw file)
    python tools/check-appkit-tokens.py --appkit ../appkit   against a local clone, no network
    python tools/check-appkit-tokens.py --write              take the file of the pinned tag, regenerate the fallback

Exit 0: in step. Exit 1: drift, the difference is printed. Exit 2: the pin cannot be read, appkit cannot be
reached (no answer is no pass), or the kit's file has a light-dark() this script cannot turn into a fallback.
"""

import argparse
import difflib
import os
import pathlib
import re
import subprocess
import sys
import urllib.request

REPO_URL = "https://github.com/StefanBartl/appkit"
RAW_URL = "https://raw.githubusercontent.com/StefanBartl/appkit/{commit}/{path}"
KIT_PATH = "ui-kit/src/tokens.css"
PIN = "tools/appkit-ui.pin"
COPY = "src/appkit-tokens.css"
FALLBACK = "src/appkit-tokens-fallback.css"

TAG = re.compile(r"^v\d+\.\d+\.\d+$")
COMMIT = re.compile(r"^[0-9a-f]{40}$")
COMMENT = re.compile(r"/\*.*?\*/", re.S)
# A token whose value is one light-dark() of two plain values. A value that only names other tokens (a color-mix()
# over --accent) needs no line of its own: it follows them, the fallback included.
LIGHT_DARK = re.compile(r"(--[\w-]+)\s*:\s*light-dark\(\s*([^,()]+?)\s*,\s*([^,()]+?)\s*\)\s*;")
DECLARATION = re.compile(r"(--[\w-]+)\s*:\s*([^;{}]*);")
# The tokens a ::backdrop reads. Before Safari 17.4 and Chromium 122 a ::backdrop inherits nothing, not even from the
# root, so `var(--backdrop)` there is empty and the shade behind a dialog is gone. Every engine that old also lacks
# light-dark(), so the fallback is the place to give the pseudo-element its own copy.
BACKDROP = ("--backdrop",)

FALLBACK_HEAD = """\
/* Generated by tools/check-appkit-tokens.py --write from src/appkit-tokens.css (appkit {tag}). Do not edit: the
   check in CI compares this file with what it generates.

   The tokens state each colour as light-dark(light, dark). A WebView without light-dark() (WKWebView before
   Safari 17.5, an older WebKitGTK) keeps those values but cannot use them, and the window would have no colours
   at all. There the same colours come from the blocks below, in the shape this window used before it took the
   kit's tokens: the system's choice, and data-theme winning over it in both directions. */
"""


class Unreachable(Exception):
    """appkit could not be asked: no network, no git, no such clone."""


def read_pin(text):
    """The tag and commit of the pin file (`key = value` lines, `#` comments)."""
    values = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep:
            raise ValueError(f"not a `key = value` line: {raw!r}")
        values[key.strip()] = value.strip()
    tag, commit = values.get("tag", ""), values.get("commit", "")
    if not TAG.match(tag):
        raise ValueError(f"the pin needs `tag = vX.Y.Z`, found {tag!r}")
    if not COMMIT.match(commit):
        raise ValueError(f"the pin needs `commit = <40 hex digits>`, found {commit!r}")
    return tag, commit


def commit_of_tag(ls_remote, tag):
    """The commit a tag names, from the output of `git ls-remote`: the peeled line of an annotated tag first."""
    refs = {}
    for line in ls_remote.splitlines():
        sha, _, ref = line.strip().partition("\t")
        refs[ref] = sha
    return refs.get(f"refs/tags/{tag}^{{}}") or refs.get(f"refs/tags/{tag}")


def git(*args):
    try:
        return subprocess.run(["git", *args], check=True, capture_output=True).stdout.decode("utf-8")
    except (OSError, subprocess.CalledProcessError) as error:
        detail = getattr(error, "stderr", b"") or b""
        raise Unreachable(f"git {' '.join(args)}: {detail.decode('utf-8', 'replace').strip() or error}")


def remote_commit(tag, appkit=None):
    if appkit:
        git("-C", appkit, "rev-parse", "--git-dir")  # no clone there: Unreachable, not "no such tag"
        try:
            return git("-C", appkit, "rev-parse", "--verify", "--quiet", f"refs/tags/{tag}^{{commit}}").strip()
        except Unreachable:
            return None
    return commit_of_tag(git("ls-remote", REPO_URL, f"refs/tags/{tag}", f"refs/tags/{tag}^{{}}"), tag)


def kit_tokens(commit, appkit=None):
    if appkit:
        return git("-C", appkit, "show", f"{commit}:{KIT_PATH}")
    url = RAW_URL.format(commit=commit, path=KIT_PATH)
    request = urllib.request.Request(url)
    # appkit is private: CI passes a read-only token (the secret PRIVATE_READ_TOKEN), a local run its own.
    token = os.environ.get("PRIVATE_READ_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read().decode("utf-8")
    except OSError as error:
        raise Unreachable(f"{url}: {error}")


def lf(text):
    return text.replace("\r\n", "\n")


def declarations(tokens_css):
    """The (name, value) of every token the file declares, comments left out, in file order."""
    return [(name, value.strip()) for name, value in DECLARATION.findall(COMMENT.sub("", tokens_css))]


def pairs(tokens_css):
    """The (name, light, dark) of every token that is a light-dark() of two plain values, in file order.

    A light-dark() in any other shape (a value with parentheses of its own, one inside a color-mix()) is an error,
    not a token left out: the fallback would lack it, and a WebView without light-dark() would have no such colour.
    """
    text = COMMENT.sub("", tokens_css)
    found = LIGHT_DARK.findall(text)
    readable = {name for name, _, _ in found}
    unreadable = [name for name, value in declarations(text) if "light-dark(" in value and name not in readable]
    if unreadable:
        raise ValueError(f"light-dark() in a shape the fallback cannot copy: {', '.join(unreadable)}")
    if not found:
        raise ValueError("no light-dark() token in the kit's file: the fallback would be empty")
    return found


def fallback(tokens_css, tag):
    """The fallback stylesheet for these tokens."""
    found = pairs(tokens_css)
    width = max(len(name) for name, _, _ in found)
    declared = dict(declarations(tokens_css))
    missing = [name for name in BACKDROP if name not in declared]
    if missing:
        raise ValueError(f"the kit's file no longer declares {', '.join(missing)}, which a ::backdrop here reads")

    def block(selector, side, indent):
        pad = " " * indent
        lines = [f"{pad}{selector} {{"]
        lines += [f"{pad}  {name}:{' ' * (width - len(name))} {values[side]};" for name, *values in found]
        return lines + [f"{pad}}}"]

    out = [FALLBACK_HEAD.format(tag=tag) + "@supports not (color: light-dark(#000, #fff)) {"]
    out += block(":root", 0, 2)
    out += ["", "  @media (prefers-color-scheme: dark) {"]
    out += block(":root:not([data-theme='light'])", 1, 4)
    out += ["  }", ""]
    out += block(":root[data-theme='dark']", 1, 2)
    out += ["", "  /* A ::backdrop inherits nothing in these engines: the tokens it reads, as the kit states them. */"]
    out += ["  ::backdrop {"] + [f"    {name}: {declared[name]};" for name in BACKDROP] + ["  }"]
    return "\n".join(out + ["}", ""])


def drift(path, want, have):
    """The lines of a unified diff from what the file should be to what it is; empty when they agree."""
    if have is not None and lf(have) == lf(want):
        return []
    if have is None:
        return [f"{path}: missing"]
    return list(
        difflib.unified_diff(
            lf(want).splitlines(), lf(have).splitlines(), f"{path} (expected)", f"{path} (in the repository)", lineterm=""
        )
    )


def read(path):
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--appkit", help="a local clone of appkit to read instead of GitHub")
    parser.add_argument("--write", action="store_true", help="write the copy and the fallback of the pinned tag")
    parser.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parent.parent), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = pathlib.Path(args.root)

    try:
        tag, pinned = read_pin(read(root / PIN) or "")
    except ValueError as error:
        print(f"{PIN}: {error}", file=sys.stderr)
        return 2
    try:
        commit = remote_commit(tag, args.appkit)
        if commit is None:
            print(f"appkit has no tag {tag}: the pin names a tag that is gone", file=sys.stderr)
            return 1
        if commit != pinned:
            print(f"the tag {tag} of appkit names {commit}, the pin says {pinned}: the tag was moved", file=sys.stderr)
            return 1
        kit = lf(kit_tokens(commit, args.appkit))
    except Unreachable as error:
        print(f"appkit cannot be reached: {error}", file=sys.stderr)
        return 2
    try:
        want = {COPY: kit, FALLBACK: fallback(kit, tag)}
    except ValueError as error:
        print(f"appkit {tag}, {KIT_PATH}: {error}", file=sys.stderr)
        return 2
    if args.write:
        for rel, text in want.items():
            (root / rel).write_bytes(text.encode("utf-8"))
            print(f"wrote {rel} ({tag})")
        return 0

    bad = False
    for rel, text in want.items():
        lines = drift(rel, text, read(root / rel))
        if lines:
            bad = True
            print("\n".join(lines))
    if bad:
        print(f"drift from appkit {tag}: run `python tools/check-appkit-tokens.py --write`", file=sys.stderr)
        return 1
    print(f"{COPY} and {FALLBACK} match appkit {tag} ({commit[:7]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
